"""Remediation branch + PR.md (D2-10, Dev2; stretch goal 2 "automated remediation PR").

After a Verified fix: commit the patched files on a LOCAL branch `guardian/fix-<finding>` in the work copy and
write PR.md (proposed fix, rationale claims with VERIFIED/INFERRED labels, validation results, rollback).
Never merges, never pushes (G5.5): the work copy has its remotes stripped and this module refuses to run if one
exists. A human opens the real PR.
"""
from __future__ import annotations

import re
import subprocess
from pathlib import Path
from typing import Any

GIT_ID = ["-c", "user.name=Guardian", "-c", "user.email=guardian@localhost", "-c", "commit.gpgsign=false"]


def _g(o: Any, k: str, default=None):
    if o is None:
        return default
    return o.get(k, default) if isinstance(o, dict) else getattr(o, k, default)


def _v(x):
    return getattr(x, "value", x)


def _git(work: Path, *args: str, check: bool = True) -> str:
    r = subprocess.run(["git", "-C", str(work), *GIT_ID, *args], capture_output=True, text=True, timeout=120)
    if check and r.returncode != 0:
        raise RuntimeError(f"git {' '.join(args[:2])} failed: {r.stderr.strip()[:300]}")
    return r.stdout.strip()


def branch_name(finding_id: str) -> str:
    return "guardian/fix-" + re.sub(r"[^A-Za-z0-9_-]", "-", finding_id)[:60]


def render_pr_md(finding: Any, plan: Any, validation: Any, approval: Any = None, base_commit: str | None = None,
                 branch: str | None = None) -> str:
    fid = _g(finding, "finding_id")
    lines = [f"# Guardian fix: {_g(finding, 'title')}", "",
             "> Generated by Guardian. **Not merged, not pushed** - review and open the PR yourself.", "",
             "## Finding", "",
             f"- **ID:** `{fid}` ({_v(_g(finding, 'category'))})",
             f"- **Component:** `{_g(finding, 'component_purl') or _g(finding, 'file_path')}`"]
    if _g(finding, "vuln_id"):
        aliases = ", ".join(_g(finding, "aliases", []) or [])
        lines.append(f"- **Vulnerability:** {_g(finding, 'vuln_id')}" + (f" ({aliases})" if aliases else ""))
    if _g(finding, "affected_range"):
        lines.append(f"- **Affected range:** `{_g(finding, 'affected_range')}`")
    paths = _g(finding, "dependency_paths", []) or []
    if paths:
        lines.append("- **Dependency path:** " + " → ".join(f"`{p}`" for p in paths[0]))
    lines.append(f"- **Evidence:** {', '.join(f'`{e}`' for e in _g(finding, 'evidence_ids', []) or [])}")

    lines += ["", "## Proposed fix", "",
              f"- **Action:** {_g(plan, 'action')}" + (f" → `{_g(plan, 'target_version')}`"
                                                        if _g(plan, "target_version") else ""),
              f"- **Plan:** `{_g(plan, 'plan_id')}` (hash `{str(_g(plan, 'plan_hash', ''))[:12]}`), "
              f"attempt {_g(plan, 'attempt')}",
              f"- **Expected risk reduction:** {_g(plan, 'expected_risk_reduction')}"]
    compat = _g(plan, "compatibility_impact")
    if compat:
        lines.append(f"- **Compatibility impact:** {_g(compat, 'level')} ({_g(compat, 'semver_delta')} "
                     f"{_g(compat, 'from_version')} → {_g(compat, 'to_version')})")
    ops = _g(plan, "ops", []) or []
    if ops:
        lines += ["", "| Op | File | Args |", "|---|---|---|"]
        lines += [f"| `{_g(o, 'op')}` | `{_g(o, 'file_path')}` | `{_g(o, 'args')}` |" for o in ops]

    claims = _g(plan, "rationale", []) or []
    if claims:
        lines += ["", "## Rationale", ""]
        for c in claims:
            label = str(_v(_g(c, "label"))).upper()
            if label == "UNSUPPORTED":
                continue  # G4.6: unsupported claims never reach the report
            cites = ", ".join(f"`{e}`" for e in _g(c, "evidence_ids", []) or [])
            lines.append(f"- **[{label}]** {_g(c, 'text')}" + (f" ({cites})" if cites else ""))

    if validation is not None:
        sb = _g(validation, "unit_tests", {}) or {}
        it = _g(validation, "integration_tests", {}) or {}
        lines += ["", "## Validation", "",
                  f"- **Verdict:** **{_g(validation, 'verdict')}** (final confidence "
                  f"{_v(_g(validation, 'final_confidence'))})",
                  f"- **Build:** {'ok' if _g(validation, 'build_ok') else 'FAILED'}",
                  f"- **Unit tests:** {sb.get('passed', 0)} passed, {sb.get('failed', 0)} failed, "
                  f"{sb.get('skipped', 0)} skipped",
                  f"- **Integration tests:** {it.get('passed', 0)} passed, {it.get('failed', 0)} failed",
                  f"- **Artifact rescanned:** {_g(validation, 'artifact_rescanned') or 'work-copy SBOM only'}",
                  f"- **Target finding resolved:** {_g(validation, 'target_finding_resolved')}",
                  f"- **New findings introduced:** {len(_g(validation, 'new_findings', []) or [])}",
                  f"- **Risk:** {_g(validation, 'risk_before')} → {_g(validation, 'risk_after')}",
                  f"- **SBOM diff evidence:** `{_g(validation, 'sbom_diff_evidence_id')}`",
                  f"- **Attempt:** `{_g(validation, 'attempt_id')}`"]
    if approval is not None:
        lines += ["", "## Approval", "",
                  f"- {_g(approval, 'decision')} by **{_g(approval, 'decided_by')}** at {_g(approval, 'ts')}"
                  + (f": {_g(approval, 'comment')}" if _g(approval, "comment") else "")]
    lines += ["", "## Rollback", "",
              f"- Plan rollback: {_g(plan, 'rollback')}",
              f"- Branch rollback: `git checkout {base_commit or '<base>'}` and delete `{branch or '<branch>'}`; "
              "nothing was merged."]
    return "\n".join(lines) + "\n"


def create_fix_branch(work: Path, finding: Any, plan: Any, validation: Any, changed_files: list[str],
                      approval: Any = None, out_dir: Path | None = None) -> dict:
    """Commit `changed_files` on a new local branch + PR.md. Only for Verified fixes. Returns branch facts."""
    work = Path(work)
    if _g(validation, "verdict") != "verified":
        raise ValueError("a remediation branch is only created for a Verified fix")
    if not (work / ".git").exists():
        raise RuntimeError("work copy is not a git repository")
    if _git(work, "remote"):
        raise RuntimeError("work copy has a git remote; refusing (G5.5: nothing is pushed)")
    base = _git(work, "rev-parse", "HEAD")
    branch = branch_name(_g(finding, "finding_id"))
    _git(work, "checkout", "-q", "-B", branch)
    pr_md = render_pr_md(finding, plan, validation, approval, base, branch)
    (work / ".guardian").mkdir(exist_ok=True)
    (work / ".guardian" / "PR.md").write_text(pr_md, encoding="utf-8")
    files = [f for f in changed_files if (work / f).exists()] + [".guardian/PR.md"]
    _git(work, "add", "-f", "--", *files)
    _git(work, "commit", "-q", "-m", f"guardian: {_g(plan, 'action')} for {_g(finding, 'title')}"[:72],
         "-m", f"Finding {_g(finding, 'finding_id')}, plan {_g(plan, 'plan_id')}, verdict verified.\n"
               "Generated by Guardian; not pushed.")
    head = _git(work, "rev-parse", "HEAD")
    if out_dir is not None:
        Path(out_dir).mkdir(parents=True, exist_ok=True)
        (Path(out_dir) / "PR.md").write_text(pr_md, encoding="utf-8")
    return {"branch": branch, "base_commit": base, "head_commit": head, "files": files,
            "pr_md": str(work / ".guardian" / "PR.md"), "pushed": False}
